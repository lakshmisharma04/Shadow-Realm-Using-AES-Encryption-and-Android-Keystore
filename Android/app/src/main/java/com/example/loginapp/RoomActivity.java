package com.example.loginapp;

import android.content.Intent;
import android.os.Bundle;
import android.view.View;
import android.widget.Button;
import android.widget.EditText;
import android.widget.TextView;

import retrofit2.Call;
import retrofit2.Callback;
import retrofit2.Response;

public class RoomActivity extends RealmActivity {
    private EditText code;
    private TextView players, hint;
    private Button action, demo;
    private String mode;

    @Override protected void onCreate(Bundle b) {
        super.onCreate(b);
        setContentView(R.layout.activity_room);
        setupTopBar("ROOM GATE", "PRIVATE MULTIPLAYER LOBBY", "ROOM");

        code = findViewById(R.id.etRoomCode);
        players = findViewById(R.id.tvPlayers);
        hint = findViewById(R.id.tvRoomHint);
        action = findViewById(R.id.btnCreateRoom);
        demo = findViewById(R.id.btnAddPlayer);
        Button start = findViewById(R.id.btnStartGame);
        TextView heading = findViewById(R.id.tvRoomHeading);

        demo.setVisibility(View.GONE);
        start.setVisibility(View.GONE);
        mode = getIntent().getStringExtra("MODE");

        if ("JOIN".equals(mode)) {
            heading.setText("JOIN THE REALM");
            hint.setText("Enter the six-character room code shared by your host.");
            action.setText("⚔  JOIN ROOM");
            code.setHint("  6-character room code");
            code.setEnabled(true);
        } else {
            heading.setText("CREATE A REALM");
            hint.setText("The server creates a unique six-character room and adds you as host.");
            action.setText("✦  CREATE PRIVATE ROOM");
            code.setHint("  generated by server");
            code.setEnabled(false);
        }

        action.setOnClickListener(v -> {
            if ("JOIN".equals(mode)) joinRoom();
            else createRoom();
        });
    }

    private void createRoom() {
        setBusy(true, "OPENING THE REALM…");
        RetrofitClient.getApiService(this).createRoom(7).enqueue(new Callback<RoomResponse>() {
            @Override public void onResponse(Call<RoomResponse> call, Response<RoomResponse> response) {
                if (response.isSuccessful() && response.body() != null) {
                    RoomResponse room = response.body();
                    OnlineSession.saveRoom(RoomActivity.this, room.getRoomCode(), true);
                    openLobby(room.getRoomCode());
                } else {
                    setBusy(false, "✦  CREATE PRIVATE ROOM");
                    Ui.toast(RoomActivity.this, "The server could not create the room.");
                }
            }
            @Override public void onFailure(Call<RoomResponse> call, Throwable t) {
                setBusy(false, "✦  CREATE PRIVATE ROOM");
                Ui.toast(RoomActivity.this, "Cannot reach Spring Boot. Check that it is running on port 8080.");
            }
        });
    }

    private void joinRoom() {
        String room = code.getText().toString().trim().toUpperCase(java.util.Locale.US);
        if (room.length() != 6) { code.setError("Room codes contain 6 characters"); return; }
        setBusy(true, "ENTERING THE REALM…");
        RetrofitClient.getApiService(this).joinRoom(room).enqueue(new Callback<RoomResponse>() {
            @Override public void onResponse(Call<RoomResponse> call, Response<RoomResponse> response) {
                if (response.isSuccessful() && response.body() != null) {
                    OnlineSession.saveRoom(RoomActivity.this, room, false);
                    openLobby(room);
                } else {
                    setBusy(false, "⚔  JOIN ROOM");
                    Ui.toast(RoomActivity.this, "That room is unavailable, full, or already started.");
                }
            }
            @Override public void onFailure(Call<RoomResponse> call, Throwable t) {
                setBusy(false, "⚔  JOIN ROOM");
                Ui.toast(RoomActivity.this, "Cannot reach the realm server.");
            }
        });
    }

    private void setBusy(boolean busy, String text) {
        action.setEnabled(!busy);
        action.setText(text);
    }

    private void openLobby(String room) {
        Intent i = new Intent(this, WaitingRoomActivity.class);
        i.putExtra("ROOM_CODE", room);
        startActivity(i);
        finish();
    }
}
